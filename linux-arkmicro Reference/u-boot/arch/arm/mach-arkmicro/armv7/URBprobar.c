unsigned int mv_RGB2Color(unsigned char r, unsigned char g, unsigned char b)
{
	if(g_bpp == 16)
		return ((r >> 3) << 11) |( (g >> 2) << 5) | (b >> 3);
	else if(g_bpp == 32)
		return (r << 16) | (g << 8) | b;
}
