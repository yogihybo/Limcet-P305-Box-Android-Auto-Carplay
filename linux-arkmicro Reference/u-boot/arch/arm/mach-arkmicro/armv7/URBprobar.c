void mv_drawLine(int x1, int y1, int x2, int y2, mv_color color)
{
	int i;
	mv_color* p;
	if ( y1 == y2 ) {
		if (x1 > x2) {
			int tmp = x1;
			x1 = x2;
			x2 = tmp;
		}
		// horz line
		p = getXYData(&s_primary, x1, y1);
		for (i = x1; i < x2; ++i)
			*p++ = color;
	}
	else if ( x1 == x2 ) {
		if (y1 > y2) {
			int tmp = y1;
			y1 = y2;
			y2 = tmp;
		}
		// vert line
		p = getXYData(&s_primary, x1,y1);
		for (i = y1; i < y2; ++i) {
			*p = color;
			p = p + s_primary.lineBytes;
		}
	}
}
